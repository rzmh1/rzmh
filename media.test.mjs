import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { randomBytes, randomUUID } from "node:crypto";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { Readable } from "node:stream";
import { setTimeout as delay } from "node:timers/promises";
import { openDatabase, saveContent } from "../server/database.mjs";
import { config } from "../server/config.mjs";
import { storageService } from "../server/storage.mjs";
const exec = promisify(execFile);
test("real local video upload converts to H264 MP4 up to 720p outside the database", async () => {
  const dir = await mkdtemp(join(tmpdir(), "ruzmah-video-")),
    cfg = config({
      DATA_DIR: dir,
      APP_KEY: randomBytes(32).toString("base64"),
    }),
    store = openDatabase(cfg);
  try {
    const id = randomUUID();
    store.db
      .prepare(
        "INSERT INTO users(id,email,name,password_hash,role,created_at) VALUES(?,?,?,?,'admin',?)",
      )
      .run(
        id,
        "media@example.test",
        "Media",
        "unused",
        new Date().toISOString(),
      );
    const source = join(dir, "sample.mp4");
    await exec("ffmpeg", [
      "-nostdin",
      "-y",
      "-f",
      "lavfi",
      "-i",
      "color=c=purple:s=320x240:d=0.5",
      "-c:v",
      "libx264",
      "-pix_fmt",
      "yuv420p",
      source,
    ]);
    const bytes = await readFile(source),
      service = storageService(store),
      u = { id, role: "admin" };
    const upload = await service.init(u, {
      name: "sample.mp4",
      mime: "video/mp4",
      size: bytes.length,
      courseId: "quant-basics",
      lessonId: "ratios",
    });
    await service.writeLocal(u, upload.id, Readable.from([bytes]));
    const linked = store.getContent();
    linked.courses[0].lessons[0].videoAssetId = upload.id;
    saveContent(store, linked, linked.revision, u.id);
    const beforeProcessing = store.getContent().revision;
    const done = await service.complete(u, upload.id, []);
    assert.equal(done.status, "processing");
    let a;
    for (let i = 0; i < 100; i++) {
      a = store.db.prepare("SELECT * FROM assets WHERE id=?").get(upload.id);
      if (a.status !== "processing") break;
      await delay(100);
    }
    assert.equal(a.status, "ready", a.error);
    assert.equal(a.mime, "video/mp4");
    assert(a.duration_seconds > 0);
    assert(
      store.getContent().revision > beforeProcessing,
      "measured duration invalidates stale study plans",
    );
    store.db
      .prepare("UPDATE assets SET duration_seconds=NULL WHERE id=?")
      .run(a.id);
    const beforeProbe = store.getContent().revision;
    const measured = await service.probe(u, a.id);
    assert(Math.abs(measured.durationSeconds - a.duration_seconds) < 0.1);
    assert(
      store.getContent().revision > beforeProbe,
      "measuring an old video refreshes its schedule",
    );
    const probe = JSON.parse(
      (
        await exec("ffprobe", [
          "-v",
          "error",
          "-show_entries",
          "stream=codec_name,width,height",
          "-of",
          "json",
          join(dir, "media", a.object_key),
        ])
      ).stdout,
    );
    assert(probe.streams[0].width <= 1280);
    assert(probe.streams[0].height <= 720);
    assert.equal(probe.streams[0].codec_name, "h264");
    await service.remove(u, a.id);
    assert.equal(
      store.db.prepare("SELECT * FROM assets WHERE id=?").get(a.id),
      undefined,
    );
  } finally {
    store.close();
    await rm(dir, { recursive: true, force: true });
  }
});
test("S3 signed upload URL is generated by the server without exposing the secret", async () => {
  const dir = await mkdtemp(join(tmpdir(), "ruzmah-s3-")),
    cfg = config({
      DATA_DIR: dir,
      APP_KEY: randomBytes(32).toString("base64"),
      STORAGE_DRIVER: "s3",
      S3_ENDPOINT: "https://s3.example.test",
      S3_BUCKET: "private-bucket",
      S3_REGION: "auto",
      S3_ACCESS_KEY_ID: "test-id",
      S3_SECRET_ACCESS_KEY: "test-secret-not-for-browser",
    }),
    store = openDatabase(cfg);
  try {
    const id = randomUUID();
    store.db
      .prepare(
        "INSERT INTO users(id,email,name,password_hash,role,created_at) VALUES(?,?,?,?,'admin',?)",
      )
      .run(id, "s3@example.test", "Media", "unused", new Date().toISOString());
    const result = await storageService(store).init(
      { id },
      { name: "image.png", mime: "image/png", size: 10, public: true },
    );
    assert.equal(result.driver, "s3");
    const url = new URL(result.urls[0]);
    assert(url.searchParams.has("X-Amz-Signature"));
    assert(!result.urls[0].includes(cfg.s3.secretAccessKey));
    assert(!url.searchParams.has("x-amz-checksum-crc32"));
    console.log(
      "Presigning is tested offline; cloud account connectivity has not been tested.",
    );
  } finally {
    store.close();
    await rm(dir, { recursive: true, force: true });
  }
});
